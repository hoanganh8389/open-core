-- 0007 Cơ chế danh mục. Lõi KHÔNG có bảng hàng / ĐVT / đối tác (R-CHAIN-0, R-PLAT-3): chỉ hai bảng cơ chế mọi app cần.
--   entity_links    ánh xạ ID của app này ↔ ID / mã của instance khác (thay ext_* của open-cake, kiot_links của open-kiot, tgs_catalog_* ).
--                   Chỉ thêm. Đổi ánh xạ = đóng valid_to của dòng cũ + thêm dòng mới; sửa / xoá khác bị chặn (trừ bizcity.purge = on).
--                   Mỗi (tenant, loại, local_id, instance) có tối đa MỘT ánh xạ canonical đang mở; mỗi remote_id cũng vậy (không gộp ngầm).
--   data_authority  chủ của một trục trong một tenant, ở CHÍNH app (không có sổ chủ trung tâm, ADR-P3 §2). App đứng riêng: local, epoch 1.
--                   epoch không bao giờ giảm (chặn chủ cũ ở W4 dựa vào điều này).
-- Chạy lại vô hại. Không cấp quyền cho vai của app (R-PLAT-1).
-- =============================================================================

CREATE TABLE IF NOT EXISTS entity_links (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  entity_type   text NOT NULL CHECK (entity_type ~ '^[a-z][a-z0-9_]{0,39}$'),
  local_id      text NOT NULL CHECK (local_id <> ''),
  peer_instance text NOT NULL CHECK (peer_instance <> ''),
  remote_id     text NOT NULL DEFAULT '',
  remote_code   text NOT NULL DEFAULT '',
  link_kind     text NOT NULL CHECK (link_kind IN ('canonical', 'alias', 'merged_from', 'proposal')),
  valid_from    timestamptz NOT NULL DEFAULT now(),
  valid_to      timestamptz,
  created_by    text NOT NULL,
  closed_by     text,
  evidence_ref  text NOT NULL DEFAULT '',
  CONSTRAINT entity_links_remote_present CHECK (remote_id <> '' OR remote_code <> ''),
  CONSTRAINT entity_links_valid_range CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
CREATE UNIQUE INDEX IF NOT EXISTS entity_links_open_local_uq ON entity_links (tenant_id, entity_type, peer_instance, local_id)
  WHERE valid_to IS NULL AND link_kind = 'canonical';
CREATE UNIQUE INDEX IF NOT EXISTS entity_links_open_remote_uq ON entity_links (tenant_id, entity_type, peer_instance, remote_id)
  WHERE valid_to IS NULL AND link_kind = 'canonical' AND remote_id <> '';
CREATE INDEX IF NOT EXISTS entity_links_local_idx ON entity_links (tenant_id, entity_type, local_id, id);
CREATE INDEX IF NOT EXISTS entity_links_code_idx ON entity_links (tenant_id, entity_type, peer_instance, remote_code) WHERE remote_code <> '';
COMMENT ON TABLE entity_links IS 'Ánh xạ ID xuyên instance (0007, NC-008 ADR-P6). Chỉ thêm; đổi = đóng valid_to + thêm dòng. Trạng thái đẩy không ở đây (ở chứng từ catalog.proposal).';
COMMENT ON COLUMN entity_links.link_kind IS 'canonical = ID của chủ; alias = tên khác còn nhận; merged_from = ID cũ đã gộp; proposal = gợi ý chờ người duyệt (không tự gộp, ADR-P2 §8).';

CREATE OR REPLACE FUNCTION bizcity_entity_links_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('bizcity.purge', true) = 'on' THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;
  -- Thao tác duy nhất được phép: đóng một dòng đang mở (đặt valid_to + closed_by), mọi cột khác giữ nguyên.
  IF TG_OP = 'UPDATE' AND OLD.valid_to IS NULL AND NEW.valid_to IS NOT NULL
     AND (NEW.id, NEW.tenant_id, NEW.entity_type, NEW.local_id, NEW.peer_instance, NEW.remote_id, NEW.remote_code, NEW.link_kind, NEW.valid_from, NEW.created_by, NEW.evidence_ref)
         IS NOT DISTINCT FROM
         (OLD.id, OLD.tenant_id, OLD.entity_type, OLD.local_id, OLD.peer_instance, OLD.remote_id, OLD.remote_code, OLD.link_kind, OLD.valid_from, OLD.created_by, OLD.evidence_ref) THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'entity_links chỉ thêm: đổi ánh xạ = đóng valid_to + thêm dòng mới (NC-008 ADR-P6)' USING ERRCODE = 'check_violation';
END $$;
DROP TRIGGER IF EXISTS entity_links_append_only ON entity_links;
CREATE TRIGGER entity_links_append_only BEFORE UPDATE OR DELETE ON entity_links
  FOR EACH ROW EXECUTE FUNCTION bizcity_entity_links_append_only();

ALTER TABLE entity_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE entity_links FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON entity_links;
CREATE POLICY tenant_isolation ON entity_links USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));

CREATE TABLE IF NOT EXISTS data_authority (
  tenant_id      bigint NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  axis           text NOT NULL CHECK (axis ~ '^[a-z][a-z0-9_]{0,39}$'),
  owner_instance text NOT NULL CHECK (owner_instance <> ''),
  epoch          integer NOT NULL DEFAULT 1 CHECK (epoch >= 1),
  state          text NOT NULL DEFAULT 'local' CHECK (state IN ('local', 'transferring', 'replica')),
  since          timestamptz NOT NULL DEFAULT now(),
  history        jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(history) = 'array'),
  PRIMARY KEY (tenant_id, axis)
);
COMMENT ON TABLE data_authority IS 'Chủ của một trục danh mục trong tenant, ghi ở chính app (0007, NC-008 ADR-P3 §2). local → transferring → replica; epoch chỉ tăng.';

CREATE OR REPLACE FUNCTION bizcity_data_authority_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('bizcity.purge', true) = 'on' THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'data_authority không xoá: chủ của trục chỉ đổi qua giao thức chuyển (NC-008 ADR-P3 §3)' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.epoch < OLD.epoch THEN
    RAISE EXCEPTION 'data_authority: epoch không được giảm (% → %)', OLD.epoch, NEW.epoch USING ERRCODE = 'check_violation';
  END IF;
  -- Đi một chiều: local → transferring → replica; huỷ chuyển transferring → local. replica không quay lại (ADR-P3 §5).
  IF OLD.state = 'replica' AND NEW.state <> 'replica' THEN
    RAISE EXCEPTION 'data_authority: replica không quay lại % (chiều ngược cần ADR riêng)', NEW.state USING ERRCODE = 'check_violation';
  END IF;
  IF OLD.state = 'local' AND NEW.state = 'replica' THEN
    RAISE EXCEPTION 'data_authority: phải qua transferring trước khi thành replica' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.state = 'replica' AND OLD.state = 'transferring' AND NEW.epoch <= OLD.epoch THEN
    RAISE EXCEPTION 'data_authority: thành replica phải tăng epoch' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS data_authority_guard ON data_authority;
CREATE TRIGGER data_authority_guard BEFORE UPDATE OR DELETE ON data_authority
  FOR EACH ROW EXECUTE FUNCTION bizcity_data_authority_guard();

ALTER TABLE data_authority ENABLE ROW LEVEL SECURITY;
ALTER TABLE data_authority FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON data_authority;
CREATE POLICY tenant_isolation ON data_authority USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));
