ALTER TABLE business_documents ADD COLUMN IF NOT EXISTS currency text NOT NULL DEFAULT 'VND';
ALTER TABLE business_documents ADD COLUMN IF NOT EXISTS fx_rate numeric(18,6) NOT NULL DEFAULT 1;
ALTER TABLE business_documents ADD COLUMN IF NOT EXISTS total_fc numeric(20,4);
ALTER TABLE business_documents ADD COLUMN IF NOT EXISTS org_unit_code text NOT NULL DEFAULT '';
ALTER TABLE business_documents ADD COLUMN IF NOT EXISTS archived_at timestamptz;
ALTER TABLE business_documents DROP CONSTRAINT IF EXISTS business_documents_currency_check;
ALTER TABLE business_documents ADD CONSTRAINT business_documents_currency_check CHECK (currency ~ '^[A-Z]{3}$');
ALTER TABLE business_documents DROP CONSTRAINT IF EXISTS business_documents_fx_rate_check;
ALTER TABLE business_documents ADD CONSTRAINT business_documents_fx_rate_check CHECK (fx_rate > 0);
COMMENT ON COLUMN business_documents.currency IS 'Tiền tệ của chứng từ, ISO 4217 (0005, R-FX-1); mặc định VND.';
COMMENT ON COLUMN business_documents.fx_rate IS 'Tỷ giá: tiền hạch toán / 1 đơn vị nguyên tệ (0005); 1 khi cùng tiền; đóng băng khi duyệt.';
COMMENT ON COLUMN business_documents.total_fc IS 'Tổng nguyên tệ (0005); NULL khi chứng từ cùng tiền hạch toán.';
COMMENT ON COLUMN business_documents.org_unit_code IS 'Nút cây tổ chức của kế toán (ledger_ref.org_unit_code, NC-007 §1); rỗng = chưa gắn.';
COMMENT ON COLUMN business_documents.archived_at IS 'Lưu trữ (ẩn khỏi danh sách mặc định, vẫn tra cứu được); không xoá chứng từ (R-DEL).';

CREATE TABLE IF NOT EXISTS document_activities (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  doc_ref     text NOT NULL,
  kind        text NOT NULL CHECK (kind IN ('create', 'transition', 'note', 'meta', 'archive', 'restore', 'system')),
  from_status text,
  to_status   text,
  reason      text NOT NULL DEFAULT '',
  body        text NOT NULL DEFAULT '',
  data        jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor       text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS document_activities_ref_idx ON document_activities (tenant_id, doc_ref, id);
COMMENT ON TABLE document_activities IS 'Hoạt động trên chứng từ (0005, NC-007 §3, chatter NC-005): tạo, chuyển trạng thái, ghi chú, đổi meta, lưu trữ / khôi phục. Chỉ thêm.';

CREATE OR REPLACE FUNCTION bizcity_document_activities_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'document_activities chỉ thêm, không sửa / xoá (R-DOCX-4)' USING ERRCODE = 'check_violation';
END $$;
DROP TRIGGER IF EXISTS document_activities_append_only ON document_activities;
CREATE TRIGGER document_activities_append_only BEFORE UPDATE OR DELETE ON document_activities
  FOR EACH ROW WHEN (current_setting('bizcity.purge', true) IS DISTINCT FROM 'on') EXECUTE FUNCTION bizcity_document_activities_append_only();

ALTER TABLE document_activities ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_activities FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON document_activities;
CREATE POLICY tenant_isolation ON document_activities USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));

